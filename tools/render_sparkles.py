def word_to_pixels(word):
    """Decode one sprite word into 8 pixel colors, SPARKLES_64x16 to SPARKLES_16x16.

    lodsw reads little-endian, then xchg ah, al swaps bytes; the resulting
    2-bit pairs (from MSB down) select the color.
    """
    s = ((word & 0xFF) << 8) | (word >> 8)
    px = []
    for k in range(8):
        v = (s >> (14 - 2 * k)) & 3
        px.append(0 if v == 0 else (1 if v < 3 else 9))
    return px


def decode_sprite(words, blocks, width):
    """Decode a sprite into a 2D grid of palette indices.

    The sprite is 'blocks' 16x16 sub-blocks side by side; each block holds
    32 words (16 rows x 2 words).
    """
    img = [[0] * width for _ in range(16)]
    for b in range(blocks):
        base = b * 32
        for row in range(16):
            for half in range(2):
                for p, color in enumerate(word_to_pixels(words[base + row * 2 + half])):
                    img[row][b * 16 + half * 8 + p] = color
    return img


