def hex_color(rgb):
    return "#%02x%02x%02x" % rgb


def draw_sprite(sprite, x, y, label):
    for r, row in enumerate(sprite):
        for c, color in enumerate(row):
            if color:
                canvas.create_rectangle(
                    x + c * SCALE, y + r * SCALE,
                    x + (c + 1) * SCALE, y + (r + 1) * SCALE,
                    fill=hex_color(COLORS[color]), outline="",
                )
            else:
                canvas.create_rectangle(
                    x + c * SCALE, y + r * SCALE,
                    x + (c + 1) * SCALE, y + (r + 1) * SCALE,
                    fill="#8c38ff", outline="",
                )
